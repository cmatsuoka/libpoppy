/*
 * mp7_tables.c - flash-resident tables for the Mini Pops library.
 *
 * The sine table stores only the first quadrant, as a file-scope `const`
 * array in flash. The full period is rebuilt once, on the first mp7_init(),
 * into a table shared by every context, every voice and every future variant
 * of the library; no context carries a copy.
 *
 * The stored values are exact: every entry equals
 *
 *     floor(32767 * sin(2*pi*i/4096) + 0.5)      for i = 0..1024
 *
 * (round-half-up, the same convention the test harness uses). The peak at
 * index 1024 is exactly 32767, and Q15 rounding makes the plateau span
 * indices 1021..1027, all at 32767. Mirroring and negation reproduce the
 * remaining quadrants exactly, so nothing is lost.
 *
 * Regenerate the table with: python3 tools/gen_sine_table.py
 *
 * This file belongs to the shared layer: the symbols are named poppy_*.
 */

