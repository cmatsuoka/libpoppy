int16_t *poppy_sine = 0;

static void rebuild_sine(int16_t *table)
{
    unsigned int i;

    for (i = 0u; i <= 1024u; i++) {
        table[i] = poppy_sine_quad1[i];
    }
    for (i = 1025u; i <= 2047u; i++) {
        table[i] = poppy_sine_quad1[2048u - i];
    }
    for (i = 2048u; i <= 3071u; i++) {
        table[i] = (int16_t)-poppy_sine_quad1[i - 2048u];
    }
    for (i = 3072u; i < POPPY_SINE_TABLE_SIZE; i++) {
        table[i] = (int16_t)-poppy_sine_quad1[4096u - i];
    }
}

void poppy_sine_init(void)
{
    static int initialized = 0;

    if (initialized) {
        return;
    }
    initialized = 1;

    poppy_sine = (int16_t *)malloc((size_t)POPPY_SINE_TABLE_SIZE *
                                   sizeof(int16_t));
    if (poppy_sine == 0) {
        return;
    }
    rebuild_sine(poppy_sine);
}

